import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const appJs = path.resolve(__dirname, '../wailsjs/go/main/App.js')
const outFile = path.resolve(__dirname, '../src/platform/app-web-generated.js')

const SPECIAL = new Set([
  'ImportSkillPackage',
  'ImportTradingRecordsFromExcel',
  'PickKBFilePath',
  'PickKBFilePaths',
  'OpenURL',
  'RestartAsAdmin',
  'HideToTray',
  'ShowFromTray',
  'QuitApp',
])

const src = fs.readFileSync(appJs, 'utf8')
const names = [...src.matchAll(/^export function (\w+)\(/gm)].map((m) => m[1])

const lines = [
  '// Generated from frontend/wailsjs/go/main/App.js — do not edit.',
  "import { rpc } from './rpc.js'",
  '',
]

for (const name of names) {
  if (SPECIAL.has(name)) {
    continue
  }
  const fn = src.match(new RegExp(`export function ${name}\\(([^)]*)\\)`))
  const args = fn && fn[1] ? fn[1].split(',').map((s) => s.trim()).filter(Boolean) : []
  const argList = args.join(', ')
  const callArgs = args.length ? ', ' + args.join(', ') : ''
  lines.push(`export function ${name}(${argList}) {`)
  lines.push(`  return rpc('${name}'${callArgs});`)
  lines.push(`}`)
  lines.push('')
}

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join('\n'))
console.log(`generated ${outFile} (${names.length - SPECIAL.size} methods)`)

const extraRPC = ['ImportSkillFromBase64', 'ImportTradingRecordsFromPath']
const allow = [...new Set([
  ...names.filter((n) => !SPECIAL.has(n)),
  ...extraRPC,
])].sort()

const goLines = [
  '// Code generated by frontend/scripts/generate-web-bridge.mjs. DO NOT EDIT.',
  '',
  'package webrpc',
  '',
  '// allowedMethods is the frontend-facing App RPC surface. Other exported',
  '// App methods (lifecycle internals, etc.) are not dispatched over HTTP.',
  'var allowedMethods = map[string]struct{}{',
]
for (const name of allow) {
  goLines.push(`\t${JSON.stringify(name)}: {},`)
}
goLines.push('}')
goLines.push('')

const goFile = path.resolve(__dirname, '../../backend/webrpc/allowlist_gen.go')
fs.mkdirSync(path.dirname(goFile), { recursive: true })
fs.writeFileSync(goFile, goLines.join('\n'))
console.log(`generated ${goFile} (${allow.length} methods)`)
